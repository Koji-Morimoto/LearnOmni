# Pylance 用に typings/pxr を生成する（Isaac Sim の pxr サブモジュールへのジャンクションを集めたスタブパッケージ）。
# システムの PYTHONPATH にある別ビルドの pxr（stub 無し）が Isaac Sim の pxr を隠してしまう問題の回避策。
# 使い方: python CodeByClaude/gen_pxr_typings.py   （extscache の拡張を更新したら再実行）
import glob
import os
import shutil
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEST = os.path.join(ROOT, "typings", "pxr")

if os.path.isdir(DEST):
    # ジャンクションはリンクだけ消す（rmdir はリンク先を消さない）
    for name in os.listdir(DEST):
        path = os.path.join(DEST, name)
        if os.path.isdir(path):
            os.rmdir(path) if os.path.islink(path) or os.path.isjunction(path) else shutil.rmtree(path)
        else:
            os.remove(path)
os.makedirs(DEST, exist_ok=True)

# 通常パッケージ扱いにして、他の場所の pxr より優先させる
with open(os.path.join(DEST, "__init__.pyi"), "w", encoding="utf-8") as f:
    f.write("# generated by CodeByClaude/gen_pxr_typings.py\n")

sources = glob.glob(os.path.join(ROOT, "extscache", "omni.usd.libs-*", "pxr")) + glob.glob(
    os.path.join(ROOT, "extscache", "omni.usd.schema.*", "pxr")
)
count = 0
for src in sources:
    for name in os.listdir(src):
        target = os.path.join(src, name)
        link = os.path.join(DEST, name)
        if not os.path.isdir(target) or name.startswith("__") or os.path.exists(link):
            continue
        subprocess.run(["cmd", "/c", "mklink", "/J", link, target], check=True, stdout=subprocess.DEVNULL)
        count += 1

print(f"{count} modules linked into {DEST}")
